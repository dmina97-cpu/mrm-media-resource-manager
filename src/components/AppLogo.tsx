function hueOf(s: string) {
  let h = 0;
  for (const c of s) h = (h * 31 + c.charCodeAt(0)) % 360;
  return h;
}

export function AppLogo({ name, size = 16 }: { name: string; size?: number }) {
  const key0 = name.trim().toLowerCase();
  const key = ALIASES[key0] ?? key0;
  const r = 5.5; // bo góc trong hệ toạ độ 24x24
  const g = GLYPHS[key];
  if (g) {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" aria-hidden="true" className="app-logo">
        <rect width="24" height="24" rx={r} fill={g.bg} />
        <g transform="translate(4 4) scale(0.6667)">
          <path d={g.path} fill="#fff" />
        </g>
      </svg>
    );
  }
  if (key === "standalone") {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" aria-hidden="true" className="app-logo">
        <rect width="24" height="24" rx={r} fill="#4A5563" />
        <path d="M6 7h12v10H6zM6 10h12" fill="none" stroke="#fff" strokeWidth="1.8" strokeLinejoin="round" />
      </svg>
    );
  }
  const b = BADGES[key];
  const text = b?.text ?? (name.trim().split(/\s+/).map((w) => w[0]).join("").slice(0, 2) || "?").toUpperCase();
  const bg = b?.bg ?? `hsl(${hueOf(key)} 45% 32%)`;
  const fg = b?.fg ?? "#fff";
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" aria-hidden="true" className="app-logo">
      <rect width="24" height="24" rx={r} fill={bg} />
      {b && b.bg !== "#000000" && (
        <rect x="1" y="1" width="22" height="22" rx={r - 1} fill="none" stroke={fg} strokeOpacity="0.55" strokeWidth="1.2" />
      )}
      <text x="12" y="16.2" textAnchor="middle" fontSize={text.length > 1 ? 10.5 : 12} fontWeight="700" fill={fg} fontFamily="Segoe UI, system-ui, sans-serif">
        {text}
      </text>
    </svg>
  );
}
